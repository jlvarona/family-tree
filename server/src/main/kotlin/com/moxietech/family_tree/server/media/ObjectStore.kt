package com.moxietech.family_tree.server.media

import java.time.Duration
import java.time.Instant

/** A presigned `PUT`: the client sends exactly [headers] and the declared number of bytes to [url] before [expiresAt]. */
data class PresignedUpload(val url: String, val headers: Map<String, String>, val expiresAt: Instant)

/** A presigned, read-only `GET` of one object, valid until [expiresAt]. */
data class PresignedDownload(val url: String, val expiresAt: Instant)

/** The result of reading an object with a size cap. */
sealed interface StoredBytes {
    /** No object under the key (for an upload: not uploaded, or not finished). */
    data object Missing : StoredBytes

    /** Larger than the cap; reading stopped there. */
    data object TooLarge : StoredBytes

    class Found(val bytes: ByteArray) : StoredBytes
}

/**
 * The object store could not be reached or refused the call. Maps to `503`; the
 * request can be retried. The cause stays in the server (it can name the bucket).
 */
class ObjectStoreUnavailableException(cause: Throwable? = null) : RuntimeException("Photo storage is unavailable", cause)

/**
 * The few object-store operations FT-008 needs, so the media service is tested
 * against a real S3-compatible service and can be wrapped to inject failures.
 * Keys are always generated by the server ([MediaKeys]); nothing here accepts a
 * key from a client. Every call may block, so implementations run off the
 * request threads; failures are [ObjectStoreUnavailableException].
 */
interface ObjectStore {
    suspend fun presignUpload(key: String, contentType: String, byteSize: Long, ttl: Duration): PresignedUpload

    suspend fun presignDownload(key: String, contentType: String, ttl: Duration): PresignedDownload

    /** Reads [key] whole, unless it is larger than [maxBytes]. */
    suspend fun read(key: String, maxBytes: Long): StoredBytes

    /** Writes [bytes] under [key], replacing any object there. */
    suspend fun write(key: String, bytes: ByteArray, contentType: String)

    /** Deletes [key]; deleting a missing key succeeds. */
    suspend fun delete(key: String)
}

/**
 * Server-generated object keys. Unverified uploads and cleaned images live under
 * different prefixes, so a bucket policy or lifecycle rule can treat them
 * differently (README "Photo storage"): `uploads/` objects are never presigned for
 * reading and can expire after a day.
 */
internal object MediaKeys {
    fun upload(treeId: kotlin.uuid.Uuid, mediaId: kotlin.uuid.Uuid) = "uploads/$treeId/$mediaId"

    /**
     * The cleaned image. Each finalization writes under its own content hash, so two
     * overlapping finalizations of one upload can never leave the stored bytes and the
     * recorded hash and dimensions describing different images.
     */
    fun stored(treeId: kotlin.uuid.Uuid, mediaId: kotlin.uuid.Uuid, sha256: String) = "media/$treeId/$mediaId/$sha256"
}
